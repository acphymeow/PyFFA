#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Two-panel comparison based on ``fig8_gaussian_kernel_benchmark.png``.

The left panel uses the smoothed NS=256 uniform-disk result corresponding to
the first panel of the source benchmark.  The right panel uses the smoothed
NS=256, source-slice-averaged Gaussian result corresponding to its last panel.
Both numerical results come from the same sampled bunch and the same 8 cm
Gaussian smoothing; no continuous model line density is used.

The numerical data are generated by ``plot_fig8_paper_kernel_comparison.py``.
That script is run automatically only when the data file is absent.
"""

from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np


HERE = Path(__file__).resolve().parent
DATA_CSV = HERE / "fig8_kernel_comparison_data.csv"
OUT_PNG = HERE / "fig8_gaussian_kernel_left_right_smooth.png"
OUT_PDF = HERE / "fig8_gaussian_kernel_left_right_smooth.pdf"
SHOW_FIGURE = False


def ensure_data():
    if DATA_CSV.exists():
        return
    from plot_fig8_paper_kernel_comparison import main as generate_data

    generate_data()


def main():
    ensure_data()
    data = np.genfromtxt(DATA_CSV, delimiter=",", names=True)
    s_relative = data["s_minus_sc_m"]
    field_theory = data["Es_3D_Gaussian_theory_V_per_m"] / 1.0e3
    field_uniform = data["Es_uniform_disk_V_per_m"] / 1.0e3
    field_gaussian = data["Es_Gaussian_V_per_m"] / 1.0e3

    plt.rcParams.update(
        {
            "font.family": "serif",
            "mathtext.fontset": "stix",
            "font.size": 10.0,
            "axes.labelsize": 11.5,
            "axes.titlesize": 11.0,
            "xtick.labelsize": 10.0,
            "ytick.labelsize": 10.0,
            "legend.fontsize": 9.0,
            "axes.linewidth": 0.9,
        }
    )

    fig, axes = plt.subplots(
        1, 2, figsize=(10.6, 3.8), sharex=True, sharey=True
    )
    panels = (
        (
            axes[0],
            field_uniform,
            "#777777",
            "(a) Uniform transverse profile + smoothing",
            "Uniform-profile calculation",
        ),
        (
            axes[1],
            field_gaussian,
            "#d62728",
            "(b) Gaussian transverse profile + smoothing",
            "Gaussian-profile calculation",
        ),
    )

    for axis, field_model, color, title, label in panels:
        axis.plot(
            s_relative,
            field_theory,
            color="#2453ff",
            lw=2.2,
            label="3D Gaussian theory",
            zorder=2,
        )
        axis.plot(
            s_relative,
            field_model,
            linestyle="none",
            marker=".",
            ms=3.0,
            color=color,
            alpha=0.9,
            label=label,
            zorder=3,
        )
        axis.axhline(0.0, color="0.35", lw=0.65, alpha=0.65)
        axis.set_title(title, loc="left")
        axis.set_xlabel(r"$s-s_c$ [m]")
        axis.grid(alpha=0.18, linewidth=0.6)
        axis.legend(loc="lower right", frameon=False)

    axes[0].set_ylabel(r"$E_s$ [kV/m]")
    fig.subplots_adjust(
        left=0.085, right=0.992, top=0.91, bottom=0.16, wspace=0.10
    )
    fig.savefig(OUT_PNG, dpi=400, bbox_inches="tight")
    fig.savefig(OUT_PDF, bbox_inches="tight")
    if SHOW_FIGURE:
        plt.show()
    plt.close(fig)

    print(f"saved: {OUT_PNG}")
    print(f"saved: {OUT_PDF}")


if __name__ == "__main__":
    main()
